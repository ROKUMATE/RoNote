#!/bin/sh
# Prints a goose migration holding River's main-line migrations FIRST to LAST,
# taken from the River version go.mod pins, so goose owns the whole schema.
# River's own migration table (River version 1) is never used.
#
#   river-migration.sh FIRST LAST     e.g. 2 8
#
# Each River migration is one goose statement block, since some define
# functions with $$ bodies. Never edit or regenerate a migration made here:
# a River upgrade adds a new one for the versions it brings.
set -eu

[ "$#" -eq 2 ] || {
  echo 'usage: river-migration.sh FIRST LAST' >&2
  exit 2
}
first=$1
last=$2
version=$(go tool river version | sed -n 's/^River version //p')

printf -- '-- River main-line migrations %s to %s, from River %s.\n' "$first" "$last" "$version"
printf -- '-- Generated by scripts/river-migration.sh from go tool river migrate-get; do not edit.\n\n'
echo '-- +goose Up'
v=$first
while [ "$v" -le "$last" ]; do
  echo '-- +goose StatementBegin'
  go tool river migrate-get --version "$v" --up
  echo '-- +goose StatementEnd'
  echo
  v=$((v + 1))
done
echo '-- +goose Down'
v=$last
while [ "$v" -ge "$first" ]; do
  echo '-- +goose StatementBegin'
  go tool river migrate-get --version "$v" --down
  echo '-- +goose StatementEnd'
  echo
  v=$((v - 1))
done
